import type { Metadata } from "next";
import type { ReactNode } from "react";

import reportData from "../../research/cell-pipeline/docs/validation_report.json";
import { ShieldCheck } from "lucide-react";

import ZoomableFigure from "../components/ZoomableFigure";
import { AmbientGlow, Eyebrow } from "../components/ui/Chrome";
import { pageShell, textLink } from "../components/ui/styles";

/*
  The report content is generated by the cell pipeline
  (research/cell-pipeline/src/build_validation_report.py) and imported
  as-is, so this page never drifts from the published numbers.
*/

type Block =
  | { type: "h1" | "h2" | "p"; text: string }
  | { type: "table"; head: string[]; rows: string[][] }
  | { type: "ul"; items: string[] };

type ValidationReport = {
  release: string;
  generated: string;
  blocks: Block[];
};

const report = reportData as ValidationReport;

export const metadata: Metadata = {
  title: "Validation report",
  description:
    "Validation report for the BioLayers AI cell pipeline: segmentation, tracking, phenotype rules and literature linking, measured on public benchmarks.",
};

const SOURCE_URL =
  "https://github.com/azizbekgayratov65-sys/biolayers-ai/tree/main/research/cell-pipeline";

// Evidence levels must never look equivalent (handoff display rule 1).
const LEVEL_STYLES: Record<string, string> = {
  observed_directly_in_image: "text-stain-dapi-bright",
  supported_by_literature: "text-stain-cy5-bright",
  inferred_by_model: "text-stain-yfp-bright",
};

const slug = (text: string) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

// Renders the **bold** and `code` markup used in the report text.
function inline(text: string): ReactNode[] {
  return text.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).map((part, i) => {
    if (part.startsWith("**") && part.endsWith("**")) {
      return (
        <strong key={i} className="font-semibold text-ink-strong">
          {part.slice(2, -2)}
        </strong>
      );
    }
    if (part.startsWith("`") && part.endsWith("`")) {
      const code = part.slice(1, -1);
      return (
        <code
          key={i}
          className={`font-mono text-[0.9em] ${LEVEL_STYLES[code] ?? "text-ink-strong"}`}
        >
          {code}
        </code>
      );
    }
    return part;
  });
}

function findTable(column: string) {
  const block = report.blocks.find((b) => b.type === "table" && b.head.includes(column));
  return block?.type === "table" ? block : undefined;
}

function cell(table: ReturnType<typeof findTable>, column: string, row = 0) {
  if (!table) return undefined;
  return table.rows[row]?.[table.head.indexOf(column)];
}

const nuclei = findTable("F1");
const tracking = findTable("SEG (mean Jaccard)");

const HIGHLIGHTS = [
  { label: "Nuclei F1", value: cell(nuclei, "F1"), note: "BBBC039, 200 images" },
  { label: "Precision", value: cell(nuclei, "Precision"), note: "Objects matched at IoU ≥ 0.5" },
  { label: "Recall", value: cell(nuclei, "Recall"), note: "Objects matched at IoU ≥ 0.5" },
  { label: "Link accuracy", value: cell(tracking, "Link accuracy"), note: "U373 time-lapse, sequence 01" },
].filter((highlight) => highlight.value);

const titleBlock = report.blocks.find((b) => b.type === "h1");
const introBlock = report.blocks.find((b) => b.type === "p");
const bodyBlocks = report.blocks.filter((b) => b !== titleBlock && b !== introBlock);
const sections = bodyBlocks.filter(
  (b): b is { type: "h1" | "h2"; text: string } => b.type === "h1" || b.type === "h2",
);

function renderBlock(block: Block, i: number) {
  switch (block.type) {
    case "h1":
    case "h2":
      return (
        <h2 key={i} id={slug(block.text)} className="mt-12 scroll-mt-24 border-b border-teal-100/[0.08] pb-3 font-serif text-xl font-bold tracking-tight text-white first:mt-0 sm:text-2xl">
          {block.text}
        </h2>
      );
    case "p":
      return (
        <p key={i} className="mt-4 max-w-prose leading-relaxed text-ink">
          {inline(block.text)}
        </p>
      );
    case "ul":
      return (
        <ul key={i} className="mt-4 max-w-prose list-disc space-y-2 pl-5 leading-relaxed text-ink marker:text-graphite">
          {block.items.map((item, j) => (
            <li key={j}>{inline(item)}</li>
          ))}
        </ul>
      );
    case "table":
      return (
        <div key={i} className="mt-5 overflow-x-auto rounded-[20px] border border-rule">
          <table className="w-full text-left text-sm">
            <thead className="border-b border-teal-100/10 bg-white/[0.03]">
              <tr>
                {block.head.map((heading) => (
                  <th key={heading} scope="col" className="px-4 py-3 font-mono text-[10px] font-semibold uppercase tracking-wider text-teal-200">
                    {heading}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-rule">
              {block.rows.map((row, r) => (
                <tr key={r}>
                  {row.map((value, c) => (
                    <td key={c} className="px-4 py-3 align-top leading-relaxed text-ink">
                      {inline(value)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      );
  }
}

